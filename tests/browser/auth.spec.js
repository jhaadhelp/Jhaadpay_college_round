import { test,expect } from '@playwright/test';
test('email signup, private collection, logout, second account isolation and returning login', async ({page}) => {
  const email='owner-'+crypto.randomUUID()+'@example.com',password='my private browser passphrase';
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Continue with Google'})).toBeDisabled();
  await page.screenshot({path:'test-results/sign-in-desktop.png',fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Your name',{exact:true}).fill('Workspace Owner');
  await page.getByLabel('Email address',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Show password'}).click();
  await expect(page.getByLabel('Password',{exact:true})).toHaveAttribute('type','text');
  await page.getByRole('button',{name:'Hide password'}).click();
  await page.getByRole('button',{name:'Create my account'}).click();
  await expect(page.getByRole('heading',{name:/Good answers/})).toBeVisible();
  await expect(page.locator('.workspace-account')).toContainText(email);
  const saved=await page.request.post('/api/collections',{data:{name:'Only the owner can read this',sources:[{name:'Secret',text:'Private content belongs to the first account.'}]}});
  expect(saved.status()).toBe(201);
  await page.getByRole('button',{name:'Sign out of account'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Your name',{exact:true}).fill('Second Person');
  await page.getByLabel('Email address',{exact:true}).fill('second-'+crypto.randomUUID()+'@example.com');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Create my account'}).click();
  await expect(page.getByRole('heading',{name:/Good answers/})).toBeVisible();
  expect(await (await page.request.get('/api/collections')).json()).toEqual([]);
  await page.getByRole('button',{name:'Sign out of account'}).click();
  await page.getByLabel('Email address',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill('incorrect password');
  await page.getByRole('button',{name:'Sign in to your workspace'}).click();
  await expect(page.getByRole('alert')).toContainText('Email or password is incorrect');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in to your workspace'}).click();
  await expect(page.getByRole('heading',{name:/Good answers/})).toBeVisible();
  const collections=await (await page.request.get('/api/collections')).json();
  expect(collections[0].name).toBe('Only the owner can read this');
});
test('mobile sign-in stays readable, handles OAuth errors, and keeps password out of URLs',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/?auth_error=google_failed');
  await expect(page.getByRole('alert')).toContainText('Google sign-in did not finish');
  expect(page.url()).not.toContain('auth_error');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Your name',{exact:true}).fill('Mobile Reviewer');
  await page.getByLabel('Email address',{exact:true}).fill('mobile-'+crypto.randomUUID()+'@example.com');
  await page.getByLabel('Password',{exact:true}).fill('a memorable private phrase');
  await page.screenshot({path:'test-results/sign-up-mobile.png',fullPage:true,animations:'disabled'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Create my account'}).click();
  await expect(page.getByRole('heading',{name:/Good answers/})).toBeVisible();
  expect(page.url()).not.toContain('phrase');
  await expect(page.getByRole('button',{name:'Sign out of account'})).toBeVisible();
  await page.request.post('/api/logout');
  await page.getByRole('button',{name:'Audit history',exact:false}).first().click();
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
});
